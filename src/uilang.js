// ── Interface language ─────────────────────────────────────────────────────
// The whole interface in English or in Russian, at the reader's choice.
//
// The interface text lives in thousands of places across App.jsx, so instead
// of threading a t() call through every one of them, the page's own text is
// translated where it lands: a MutationObserver watches the document and any
// text node (or title / placeholder / aria-label) whose words are a known
// interface string is swapped for its Russian. React is not disturbed by
// this — it only rewrites a text node when its own value for it changes, and
// when it does, the observer sees the new English and translates that too.
//
// Only whole strings in the table below are touched, so the books, the
// dictionary's glosses, readers' notes, chat and the forum are left as they
// are; anything marked lang="ru" or data-noxl is skipped outright.

export var UI_LANG_KEY = "gv_ui_lang";

export function readUiLang() {
  try {
    var v = localStorage.getItem(UI_LANG_KEY);
    if (v === "ru" || v === "en") return v;
  } catch (e) {}
  return "en";
}
export function saveUiLang(v) {
  try { localStorage.setItem(UI_LANG_KEY, v); } catch (e) {}
}

function pl(n, one, few, many) {
  n = Math.abs(n) % 100;
  var n1 = n % 10;
  if (n > 10 && n < 20) return many;
  if (n1 > 1 && n1 < 5) return few;
  if (n1 === 1) return one;
  return many;
}

