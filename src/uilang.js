// The Russian for one piece of interface text, or null to leave it be.
export function trUi(raw, el, inBook) {
  if (!raw || !LATIN.test(raw)) return null;
  var lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
  var core = raw.replace(/\s+/g, " ").trim();
  if (!core) return null;
  var hit = lookup(core, el);
  if (hit != null) return lead + hit + trail;
  if (inBook) return null;            // the book's own words: exact strings only
  var n = numbered(core);
  if (n != null) return lead + n + trail;
  var pre = (core.match(LEAD) || [""])[0];
  var post = (core.slice(pre.length).match(TRAIL) || [""])[0];
  var mid = core.slice(pre.length, core.length - post.length);
  if (mid && (pre || post)) {
    hit = lookup(mid, el);
    if (hit == null) hit = numbered(mid);
    if (hit != null) return lead + pre + hit + post + trail;
  }
  return null;
}

