// Same normalization convention as normWordForAlign in App.jsx (lowercase,
// ё → е, drop punctuation) but spaces are preserved so multi-word entries
// like "друг друга" still match.
export function normCommonWord(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/\u0451/g, "\u0435")
    .replace(/[^\u0430-\u044fa-z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

var COMMON_RU_SET = (function () {
  var s = Object.create(null);
  for (var i = 0; i < COMMON_RU_WORDS.length; i++) {
    var k = normCommonWord(COMMON_RU_WORDS[i]);
    if (k) s[k] = 1;
  }
  return s;
})();

// True when `s` is a word the learner has already declared known.
export function isCommonWord(s) {
  var k = normCommonWord(s);
  if (!k) return false;
  if (COMMON_RU_SET[k]) return true;
  // Verbs are often written "быть (to be)" or "идти/пойти" upstream — check the
  // leading token too so those variants still get caught.
  var head = k.split(/[ \/(]/)[0];
  return !!(head && COMMON_RU_SET[head]);
}

// Drops any entry whose Russian side is already known. `get` pulls the Russian
// string out of an item (defaults to the item itself, or its .ru field).
export function dropCommonWords(items, get) {
  if (!Array.isArray(items)) return [];
  var pick = get || function (x) { return x && typeof x === "object" ? x.ru : x; };
  return items.filter(function (x) { return !isCommonWord(pick(x)); });
}

